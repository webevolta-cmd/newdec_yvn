"""Writes CATALOG-COVERAGE.md from the curated catalog and the texture build report.

  python3 -I scripts/assets/coverage.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TEX = ROOT / "assets-src" / "textures"

TILING = {
    "module": "fills each sheet/tile; joints true to size",
    "repeat": "true scale",
}


def main() -> None:
    cat = json.loads((TEX / "catalog.json").read_text())
    report = {r["id"]: r for r in json.loads((TEX / "build-report.json").read_text())}
    names = cat["categoryNames"]
    products = cat["products"]
    lines = [
        "# Catalog and visualizer coverage",
        "",
        "Generated by `scripts/assets/coverage.py` from `assets-src/textures/catalog.json` and the texture",
        "build report. Every product below appears in the catalog and in the visualizer, and links to the",
        "NEW DEC TikTok video its reference was photographed from.",
        "",
        f"**{len(products)} products** in the catalog and visualizer; **{len(cat['gaps'])}** items seen without a usable",
        f"reference; **{len(cat.get('excluded', []))}** deliberately excluded.",
        "",
        "## Sources and their limits",
        "",
        "- The only sources were NEW DEC's own public TikTok videos (10 of the 31 videos on the profile could be",
        "  opened) and public map listings. The Instagram profile could not be opened without logging in, so",
        "  anything shown only on Instagram is not covered here.",
        "- References are frames of phone videos (576×1024 or 720×1280), so they were rectified from",
        "  perspective, cleaned of glare where needed and upscaled. They show the look of each panel, not",
        "  a colour-calibrated sample: colours and fine detail should be confirmed in the showroom.",
        "- Names are descriptive Armenian names written for the site. NEW DEC's own product names or codes were",
        "  not visible and should replace them.",
        "",
        "## Scale and joints in the visualizer",
        "",
        "- Sheet size 1,22 × 2,80 m is used for joints of all sheet products. NEW DEC states 2,80 or 2,90 × 1,22 m",
        "  for marble sheets; 2,80 m is used because the illustrative wall is 2,80 m high.",
        "- Stone relief tiles use 0,60 × 1,20 m (stated). Slat panels use a 0,60 m panel width, counted from the",
        "  slats in the video; slat panels have no visible joint.",
        "- Wood, plain and travertine sheets: the module size is not stated by NEW DEC; the standard 1,22 m sheet",
        "  width is assumed for the joints.",
        "- \"fills each sheet\" means the photographed fragment of the panel was scaled up uniformly to fill one",
        "  sheet, like identical printed sheets. The factor below says how much the pattern is enlarged compared",
        "  with the photographed fragment. For wood, slats and travertine the fragment is fitted to the sheet height",
        "  along the grain, which keeps the spacing across the grain true.",
        "",
        "## Products",
        "",
        "| # | Name on the site | Category | Size / thickness shown | Reference | Pattern scale |",
        "|---|---|---|---|---|---|",
    ]
    for i, p in enumerate(products, 1):
        r = report.get(p["id"], {})
        spec = " · ".join(v for v in (p.get("size"), p.get("thickness")) if v) or "not stated"
        src = p["source"]
        ref = f"[{src['video']}](https://www.tiktok.com/@newdec_yvn/video/{src['video']}) at {src['time']}"
        scale = r.get("scale", 1)
        mode = TILING.get(r.get("tiling", ""), r.get("tiling", ""))
        scale_txt = f"{mode}, ×{scale:g}" if r.get("tiling") == "module" else mode
        lines.append(f"| {i} | {p['name']} (`{p['id']}`) | {names[p['category']]} | {spec} | {ref} | {scale_txt} |")
    lines += ["", "## Seen without a usable reference (not on the site)", "", "| Item | Why |", "|---|---|"]
    for g in cat["gaps"]:
        lines.append(f"| {g['name']} (`{g['id']}`) | {g['reason'].replace('|', '/').strip()} |")
    lines += ["", "## Deliberately excluded", "", "| Item | Why |", "|---|---|"]
    for g in cat.get("excluded", []):
        lines.append(f"| {g['name']} (`{g['id']}`) | {g['reason']} |")
    lines += [
        "",
        "## To complete the catalog",
        "",
        "Owner photos of each sheet, taken straight-on in even light with the sheet's code, would replace the",
        "video references above, fill the gaps and allow true-scale patterns. Put each photo through",
        "`scripts/assets/make_texture.py`, add it to `scripts/assets/curation.py`, and rebuild (see README).",
        "",
    ]
    (ROOT / "CATALOG-COVERAGE.md").write_text("\n".join(lines))
    print(f"CATALOG-COVERAGE.md: {len(products)} products, {len(cat['gaps'])} gaps")


if __name__ == "__main__":
    main()
